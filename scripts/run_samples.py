"""Run the PR risk agent on a repo's most recently merged PRs and save the results (SPEC_W3 D5).

    uv run python scripts/run_samples.py encode/httpx --limit 10
    uv run python scripts/run_samples.py encode/httpx --prs 3672 3670   # (re-)run just these

Writes docs/results/w3_samples/<pr>.json (PR, verdict, trace) and rebuilds summary.md there from
every saved result, so re-running a few PRs (e.g. after a rate limit) keeps the rest.
Needs LLM_PROVIDER, LLM_MODEL, the provider's API key and its prices in .env; costs real money.
"""

import argparse
import asyncio
from pathlib import Path
from typing import Any

from agent.github import GitHubClient
from agent.llm import make_chat_model
from agent.service import AgentRun, assess_pr
from redis.asyncio import Redis
from shipwatch_common.logging import configure_logging
from worker.settings import WorkerSettings

OUT = Path(__file__).resolve().parents[1] / "docs/results/w3_samples"


async def recent_merged(gh: GitHubClient, repo: str, limit: int) -> list[dict[str, Any]]:
    """The `limit` most recently merged PRs (closed-but-unmerged ones are skipped)."""
    pulls, _ = await gh.get_pages(
        f"/repos/{repo}/pulls",
        {"state": "closed", "sort": "updated", "direction": "desc", "per_page": 100},
        max_pages=3,
    )
    merged = [p for p in pulls if p.get("merged_at")]
    merged.sort(key=lambda p: p["merged_at"], reverse=True)
    return merged[:limit]


def _save(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text if text.endswith("\n") else text + "\n")


def top_factor(run: AgentRun) -> str:
    a = run.verdict.assessment
    if not a or not a.factors:
        return "-"
    f = max(a.factors, key=lambda f: f.severity)
    return f"{f.kind} ({f.severity})"


class Sample(AgentRun):
    """What one <pr>.json holds: the PR's number, title and merge time, plus the agent run."""

    pr: dict[str, Any]


def load_samples(out: Path) -> list[Sample]:
    samples = [Sample.model_validate_json(f.read_text()) for f in out.glob("*.json")]
    samples.sort(key=lambda s: s.pr.get("merged_at") or "", reverse=True)
    return samples


def summary_table(samples: list[Sample], repo: str) -> str:
    models = sorted({f"{s.trace.provider}:{s.trace.model}" for s in samples})
    lines = [
        f"# W3 sample runs: {repo}",
        "",
        f"Model: `{', '.join(models)}`. Generated by `scripts/run_samples.py` from the JSON files "
        "here (one per PR).",
        "",
        "| PR | Title | Level | Score | Top factor | Tool calls | Tokens (in/out) | Latency "
        "| Cost |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for s in samples:
        v, t, n = s.verdict, s.trace, s.pr["number"]
        title = s.pr["title"].replace("|", "\\|")[:60]
        lines.append(
            f"| [#{n}](https://github.com/{repo}/pull/{n}) | {title} "
            f"| {v.level} | {v.score if v.score is not None else '-'} | {top_factor(s)} "
            f"| {t.tool_calls} | {t.input_tokens}/{t.output_tokens} "
            f"| {t.latency_ms / 1000:.1f} s | ${t.cost_usd:.4f} |"
        )
    done = [s.trace for s in samples if s.verdict.level != "needs_review"]
    if samples:
        cost = sum(s.trace.cost_usd for s in samples)
        lines += ["", f"{len(done)} of {len(samples)} scored; total cost ${cost:.4f}."]
    if done:
        latency = sum(t.latency_ms for t in done) / len(done) / 1000
        tokens = sum(t.input_tokens + t.output_tokens for t in done) / len(done)
        lines.append(f"Scored PRs: mean latency {latency:.1f} s, mean tokens {tokens:.0f}.")
    return "\n".join(lines) + "\n"


async def run_samples(
    repo: str, settings: WorkerSettings, out: Path, *, limit: int = 10, prs: list[int] | None = None
) -> str:
    llm = make_chat_model(settings)
    redis = Redis.from_url(settings.redis_url, socket_connect_timeout=1)
    try:
        async with GitHubClient.from_settings(settings, redis) as gh:
            if prs:
                targets = [await gh.get_json(f"/repos/{repo}/pulls/{n}") for n in prs]
            else:
                targets = await recent_merged(gh, repo, limit)
            for pr in targets:
                run = await assess_pr(llm, gh, repo, pr["number"], settings)
                meta = {k: pr.get(k) for k in ("number", "title", "merged_at")}
                sample = Sample(pr=meta, verdict=run.verdict, trace=run.trace)
                await asyncio.to_thread(
                    _save, out / f"{pr['number']}.json", sample.model_dump_json(indent=2)
                )
                v = run.verdict
                print(f"#{pr['number']}: {v.level} {v.score if v.score is not None else ''}")
    finally:
        await redis.aclose()
    table = summary_table(await asyncio.to_thread(load_samples, out), repo)
    await asyncio.to_thread(_save, out / "summary.md", table)
    return table


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("repo", help="owner/name")
    parser.add_argument("--limit", type=int, default=10, help="most recently merged PRs")
    parser.add_argument("--prs", type=int, nargs="+", help="run exactly these PR numbers")
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--max-retries", type=int, default=6, help="SDK retries on rate limits")
    parser.add_argument("--timeout", type=float, default=600, help="per-PR agent timeout (s)")
    args = parser.parse_args()
    configure_logging("WARNING")
    # Unlike the worker, a batch run should wait out provider rate limits (free tiers have small
    # tokens-per-minute limits) rather than record needs_review, so let the SDK retry and allow
    # for the waits. Latency in the table then includes that waiting.
    settings = WorkerSettings().model_copy(
        update={"llm_max_retries": args.max_retries, "agent_timeout_seconds": args.timeout}
    )
    print(asyncio.run(run_samples(args.repo, settings, args.out, limit=args.limit, prs=args.prs)))


if __name__ == "__main__":
    main()
